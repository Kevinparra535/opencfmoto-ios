final class CanvasFitGoldenTests: XCTestCase {
    func testViewportsAndInverseMatchKotlin() {
        var v = 0, i = 0
        for line in Self.data.split(separator: "\n") {
            let f = line.split(separator: " ").map(String.init)
            if f[0] == "V" {
                let n = f[1...8].map { Int($0)! }
                let mode = ScreenFit(rawValue: f[9])!
                let got = CanvasFit.viewport(canvasWidth: n[0], canvasHeight: n[1], sourceWidth: n[2], sourceHeight: n[3], mode: mode,
                                             margins: ScreenMargins(customised: true, top: n[4], bottom: n[5], left: n[6], right: n[7]))
                let want: CanvasViewport? = f[10] == "nil" ? nil : CanvasViewport(x: Int(f[10])!, y: Int(f[11])!, width: Int(f[12])!, height: Int(f[13])!)
                XCTAssertEqual(got, want, String(line))
                v += 1
            } else {
                let n = f[1...8].map { Int($0)! }
                let got = CanvasFit.mapCanvasToSource(x: n[6], y: n[7], viewport: CanvasViewport(x: n[0], y: n[1], width: n[2], height: n[3]),
                                                      sourceWidth: n[4], sourceHeight: n[5]).map { [$0.x, $0.y] }
                let want: [Int]? = f[9] == "nil" ? nil : [Int(f[9])!, Int(f[10])!]
                XCTAssertEqual(got, want, String(line))
                i += 1
            }
        }
        XCTAssertEqual(v, 1458)
        XCTAssertGreaterThan(i, 100)
    }
}

