// Golden vectors from the UPSTREAM Kotlin AdaptivePolicy (AdaptiveVideoController.kt) on a JVM:
// lines `<base> <baseFps> <thermal> <prevLink bits> <drops> <bitrate> <fps> <link bits>` (every 4th of a
// 3920-case grid), plus a 140-step AIMD chain.

import XCTest
@testable import OpenCfMotoCore

final class AdaptiveGoldenTests: XCTestCase {
    func testDecideMatchesKotlin() {
        var n = 0
        for line in Self.grid.split(separator: "\n") {
            let f = line.split(separator: " ").map(String.init)
            let prev = Float(bitPattern: UInt32(f[3], radix: 16)!)
            let d = AdaptivePolicy.decide(baseBitrate: Int(f[0])!, baseFps: Int(f[1])!, thermalStatus: Int(f[2])!,
                                          prevLinkFactor: prev, dropsThisTick: Int(f[4])!)
            XCTAssertEqual(d.bitrate, Int(f[5])!, String(line))
            XCTAssertEqual(d.fps, Int(f[6])!, String(line))
            XCTAssertEqual(d.linkFactor.bitPattern, UInt32(f[7], radix: 16)!, String(line))
            n += 1
        }
        XCTAssertEqual(n, 980)
    }

    func testAIMDChainMatchesKotlin() {
        let pattern = [100, 100, 0, 8, 7, 100, 0, 0, 0, 100, 100, 100, 100, 0]
        var f: Float = 1.0
        for (k, hex) in Self.chain.split(separator: " ").dropFirst().enumerated() {
            f = AdaptivePolicy.nextLinkFactor(f, dropsThisTick: pattern[k % pattern.count])
            XCTAssertEqual(f.bitPattern, UInt32(hex, radix: 16)!, "step \(k)")
        }
    }
}

