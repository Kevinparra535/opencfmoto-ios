import XCTest
@testable import OpenCfMotoCore

final class SettingsJavaNumberGoldenTests: XCTestCase {
    func testJavaNumberFormattingMatchesJDK() {
        var checked = 0
        for line in Self.numbers.split(separator: "\n") {
            let f = line.split(separator: " ").map(String.init)
            guard f.count == 4, let bits = UInt64(f[0], radix: 16) else { return XCTFail("bad line \(line)") }
            let d = Double(bitPattern: bits)
            XCTAssertEqual(AppJavaNumber.doubleToString(d), f[1], "toString \(f[0])")
            XCTAssertEqual(AppJavaNumber.formatFixed(d, precision: 2), f[2], "%.2f \(f[0]) \(f[1])")
            XCTAssertEqual(AppJavaNumber.formatFixed(d, precision: 6), f[3], "%.6f \(f[0]) \(f[1])")
            if let parsed = AppJavaNumber.parseDouble(f[1]) { XCTAssertEqual(parsed.bitPattern, d.bitPattern, "parse \(f[1])") }
            else { XCTFail("parseDouble \(f[1])") }
            checked += 1
        }
        XCTAssertGreaterThan(checked, 1000)
    }
}

