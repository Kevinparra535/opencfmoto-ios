#!/usr/bin/env python3
"""Generate stubs/java/dev/zanderp/opencfmoto/R.java (HARNESS STUB) for the copied upstream files.

Every R.<type>.<name> referenced by harness/upstream/**.kt gets an id; R.text(id) returns the
English string from the upstream res/values/strings.xml so Context.getString() matches the app.
"""
import pathlib, re, sys, xml.etree.ElementTree as ET

here = pathlib.Path(__file__).resolve().parent
up = here / "upstream"
import os
strings_xml = pathlib.Path(os.environ.get("UPSTREAM", str(here / "../../../open-cfmoto"))) / "app/src/main/res/values/strings.xml"
refs = {}
for f in sorted(up.rglob("*.kt")):
    for m in re.finditer(r"(?<![\w.])R\.(string|style|layout|drawable|id|color|dimen)\.(\w+)", f.read_text()):
        refs.setdefault(m.group(1), set()).add(m.group(2))

texts = {}
root = ET.parse(strings_xml).getroot()
for el in root.findall("string"):
    t = "".join(el.itertext())
    if len(t) >= 2 and t[0] == '"' and t[-1] == '"':
        t = t[1:-1]
    t = t.replace("\\'", "'").replace('\\"', '"').replace("\\n", "\n").replace("\\@", "@").replace("\\?", "?")
    texts[el.get("name")] = t

def jstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'

base = {"string": 0x7F100000, "style": 0x7F110000, "layout": 0x7F0C0000, "drawable": 0x7F080000,
        "id": 0x7F090000, "color": 0x7F060000, "dimen": 0x7F070000}
lines = ["// HARNESS STUB (generated by harness/gen_r.py — not Android code). Stand-in for the app's",
         "// generated R class; ids are arbitrary, R.text() returns res/values/strings.xml text.",
         "package dev.zanderp.opencfmoto;", "", "import java.util.HashMap;", "import java.util.Map;", "",
         "public final class R {", "    private R() {}",
         "    private static final Map<Integer, String> TEXT = new HashMap<>();",
         "    public static String text(int id) { return TEXT.get(id); }"]
static_init = ["    static {"]
for typ in sorted(refs):
    lines.append(f"    public static final class {typ} {{")
    lines.append(f"        private {typ}() {{}}")
    for i, name in enumerate(sorted(refs[typ]), start=1):
        rid = base[typ] + i
        lines.append(f"        public static final int {name} = 0x{rid:08x};")
        if typ == "string":
            if name not in texts:
                print(f"warning: no strings.xml entry for {name}", file=sys.stderr)
            static_init.append(f"        TEXT.put(0x{rid:08x}, {jstr(texts.get(name, name))});")
    lines.append("    }")
static_init.append("    }")
lines += static_init + ["}", ""]
out = here / "stubs/java/dev/zanderp/opencfmoto/R.java"
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text("\n".join(lines))
print(f"wrote {out}: " + ", ".join(f"{k}={len(v)}" for k, v in sorted(refs.items())))
